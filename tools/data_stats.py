"""Run db/checks.sql on the metadata database and write reports/analysis/data_stats.md
with the query results and two histograms.

Usage (repo root, venv active, after tools/build_db.py):
    python tools/data_stats.py
    python tools/data_stats.py --db output/test.sqlite --out output/data_stats_test.md
Real reference: scratch areas from the 10 seen_pool ground-truth masks only
(leakage-safe; locked_test is never read).
"""
import argparse
import re
import sqlite3
from pathlib import Path

import cv2
import matplotlib.pyplot as plt
import numpy as np

REAL_ROOT = Path("data/real/mvtec/metal_nut")
SYNTH_PIXELS = 512 * 512
# chart style (reference palette: categorical slots 1-2, recessive text/grid)
BLUE, ORANGE = "#2a78d6", "#eb6834"
INK, INK_2, SURFACE = "#0b0b0b", "#52514e", "#fcfcfb"

parser = argparse.ArgumentParser()
parser.add_argument("--db", type=Path, default=Path("db/meta.sqlite"))
parser.add_argument("--out", type=Path, default=Path("reports/analysis/data_stats.md"))
args = parser.parse_args()
con = sqlite3.connect(args.db)


def markdown_table(cursor):
    cols = [c[0] for c in cursor.description]
    rows = cursor.fetchall()
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    lines += ["| " + " | ".join(str(v) for v in r) + " |" for r in rows]
    return "\n".join(lines)


def style(ax, title, xlabel, ylabel):
    ax.set_title(title, color=INK, loc="left", fontsize=11)
    ax.set_xlabel(xlabel, color=INK_2)
    ax.set_ylabel(ylabel, color=INK_2)
    ax.tick_params(colors=INK_2)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    for side in ("left", "bottom"):
        ax.spines[side].set_color("#d0cfca")
    ax.grid(axis="y", color="#ecebe7", linewidth=0.8)
    ax.set_axisbelow(True)


# --- 1) query results -----------------------------------------------------------
sql = Path("db/checks.sql").read_text()
blocks = re.split(r"^-- name: ", sql, flags=re.M)[1:]
sections = []
for block in blocks:
    title, _, body = block.partition("\n")
    comments = [l[3:] for l in body.splitlines() if l.startswith("-- ")]
    query = "\n".join(l for l in body.splitlines() if not l.startswith("--")).strip()
    sections.append(f"### {title}\n{' '.join(comments)}\n\n{markdown_table(con.execute(query))}")

# --- 2) histogram: scratch area per image, synthetic vs real seen_pool ----------
# per image (not per scratch): a real mask holds all scratches of the image in one
synth_area = np.array([a for (a,) in con.execute(
    "SELECT SUM(area_px) FROM defects GROUP BY image_id HAVING SUM(area_px) > 0")]) / SYNTH_PIXELS * 100
real_area = []
for rel in Path("splits/seen_pool.txt").read_text().split():
    p = Path(rel)
    mask = cv2.imread(str(REAL_ROOT / "ground_truth" / p.parent.name / f"{p.stem}_mask.png"), 0)
    real_area.append(100 * (mask > 0).mean())
real_area = np.array(real_area)

fig, ax = plt.subplots(figsize=(7, 3.6), facecolor=SURFACE)
ax.set_facecolor(SURFACE)
bins = np.arange(0, max(synth_area.max(), real_area.max()) + 1, 0.5)
ax.hist(synth_area, bins=bins, density=True, color=BLUE, edgecolor=SURFACE, linewidth=1.5,
        label=f"synthetic images (n={len(synth_area)})")
ax.plot(real_area, np.zeros_like(real_area), "|", color=ORANGE, markersize=22, mew=2.5,
        label=f"real seen_pool images (n={len(real_area)})", clip_on=False)
style(ax, "Scratch area per defective image, synthetic vs real", "scratch mask area (% of image)", "density")
ax.legend(frameon=False, labelcolor=INK_2)
fig.tight_layout()
args.out.parent.mkdir(parents=True, exist_ok=True)
area_png = args.out.with_name(args.out.stem + "_area.png")
fig.savefig(area_png, dpi=150)

# --- 3) histogram: scratches per image -----------------------------------------
counts = dict(con.execute("SELECT n_defects, COUNT(*) FROM images GROUP BY n_defects"))
total = sum(counts.values())
xs = [0, 1, 2, 3]
ys = [100 * counts.get(x, 0) / total for x in xs]
fig, ax = plt.subplots(figsize=(5, 3.4), facecolor=SURFACE)
ax.set_facecolor(SURFACE)
bars = ax.bar(xs, ys, color=BLUE, width=0.6, edgecolor=SURFACE, linewidth=1.5)
ax.bar_label(bars, labels=[f"{y:.0f}%" for y in ys], color=INK_2, padding=2)
ax.set_xticks(xs)
style(ax, f"Scratches per image (n={total} images)", "scratches in the image", "% of images")
fig.tight_layout()
count_png = args.out.with_name(args.out.stem + "_per_image.png")
fig.savefig(count_png, dpi=150)

# --- 4) write the report --------------------------------------------------------
n_img, = con.execute("SELECT COUNT(*) FROM images").fetchone()
versions = ", ".join(v for (v,) in con.execute("SELECT DISTINCT dataset_version FROM images"))
args.out.write_text(f"""# Synthetic data statistics

Dataset: {versions}, {n_img} images. Generated by `tools/data_stats.py` from
`{args.db}` (queries: `db/checks.sql`).

{(chr(10) * 2).join(sections)}

### Histograms

![Scratch area]({area_png.name})

Total scratch area per defective image. Real reference = the 10 seen_pool
scratch masks (700x700, area as % of image),
median {np.median(real_area):.1f}%, range {real_area.min():.1f}-{real_area.max():.1f}%.
Synthetic median {np.median(synth_area):.1f}%.

![Scratches per image]({count_png.name})
""")
print(f"wrote {args.out}, {area_png}, {count_png}")
